/*
Q1. Calculate total revenue generated by each customer and show
    each customer's percentage contribution to overall revenue.
*/

WITH Customer_Revenue AS (
    SELECT
        o.Customer_ID,
        SUM(
            oi.Quantity * oi.Unit_Price
        ) AS Revenue
    FROM CO.Orders o
    INNER JOIN CO.Order_Items oi
        ON o.Order_Id = oi.Order_Id
    GROUP BY o.Customer_ID
)

SELECT
    Customer_ID,
    Revenue,

    ROUND(
        Revenue * 100.0
        / SUM(Revenue) OVER (),
        2
    ) AS Revenue_Pct

FROM Customer_Revenue

ORDER BY Revenue DESC;


/*
Q2. Find the top 10 customers by revenue and show their
    percentage contribution to total company revenue.
*/

WITH Customer_Revenue AS (
    SELECT
        o.Customer_ID,
        SUM(
            oi.Quantity * oi.Unit_Price
        ) AS Revenue
    FROM CO.Orders o
    INNER JOIN CO.Order_Items oi
        ON o.Order_Id = oi.Order_Id
    GROUP BY o.Customer_ID
),

Ranked_Customers AS (
    SELECT
        Customer_ID,
        Revenue,

        RANK() OVER (
            ORDER BY Revenue DESC
        ) AS Revenue_Rank

    FROM Customer_Revenue
)

SELECT
    Customer_ID,
    Revenue,
    Revenue_Rank,

    ROUND(
        Revenue * 100.0
        / SUM(Revenue) OVER (),
        2
    ) AS Revenue_Pct

FROM Ranked_Customers

WHERE Revenue_Rank <= 10

ORDER BY Revenue_Rank;


