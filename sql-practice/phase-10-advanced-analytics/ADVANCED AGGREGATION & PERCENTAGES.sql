/*
Q4. Calculate the cumulative percentage of total revenue
    contributed by customers ordered from highest to lowest revenue.
*/

WITH Customer_Revenue AS (
    SELECT
        o.Customer_ID,

        SUM(
            oi.Quantity * oi.Unit_Price
        ) AS Revenue

    FROM CO.Orders o

    INNER JOIN CO.Order_Items oi
        ON o.Order_Id = oi.Order_Id

    GROUP BY o.Customer_ID
),

Customer_Cumulative AS (
    SELECT
        Customer_ID,
        Revenue,

        SUM(Revenue) OVER (
            ORDER BY Revenue DESC
            ROWS BETWEEN UNBOUNDED PRECEDING
                     AND CURRENT ROW
        ) AS Cumulative_Revenue,

        SUM(Revenue) OVER () AS Total_Revenue

    FROM Customer_Revenue
)

SELECT
    Customer_ID,
    Revenue,
    Cumulative_Revenue,

    ROUND(
        Cumulative_Revenue * 100.0
        / Total_Revenue,
        2
    ) AS Cumulative_Revenue_Pct

FROM Customer_Cumulative

ORDER BY Revenue DESC;


/*
Q5. Find the customers responsible for the first 80% of
    total revenue.
*/

WITH Customer_Revenue AS (
    SELECT
        o.Customer_ID,

        SUM(
            oi.Quantity * oi.Unit_Price
        ) AS Revenue

    FROM CO.Orders o

    INNER JOIN CO.Order_Items oi
        ON o.Order_Id = oi.Order_Id

    GROUP BY o.Customer_ID
),

Revenue_Cumulative AS (
    SELECT
        Customer_ID,
        Revenue,

        SUM(Revenue) OVER (
            ORDER BY Revenue DESC
            ROWS BETWEEN UNBOUNDED PRECEDING
                     AND CURRENT ROW
        ) AS Running_Revenue,

        SUM(Revenue) OVER () AS Total_Revenue

    FROM Customer_Revenue
)

SELECT
    Customer_ID,
    Revenue,

    ROUND(
        Running_Revenue * 100.0
        / Total_Revenue,
        2
    ) AS Cumulative_Revenue_Pct

FROM Revenue_Cumulative

WHERE Running_Revenue <=
      Total_Revenue * 0.80

ORDER BY Revenue DESC;


